class RiskToolInputSchema(BaseModel):
    """
    Input schema for the Risk Tool (serve as inputs to the risk agent so validation is done there).
    """

    inputs: List[str] = Field(
        ...,
        description="A list of user inputs/messages, ordered chronologically as part of a conversation.",
    )
    outputs: List[str] = Field(
        ...,
        description="A list of model outputs/responses, aligned with the `inputs` by index.",
    )
    risk_ids: List[str] = Field(
        ...,
        description="A list of risk IDs to evaluate against. These should match keys in the risk definitions "
        "YAML file or science risks yaml file (or any custom risk yaml file with the same structure)..",
    )
    risk_weights: Optional[Dict[str, float]] = Field(
        default=None,
        description=(
            "Optional per-risk weight overrides. Keys must be a subset of `risk_ids` and values must be positive. "
            "Any risk not listed here defaults to 1.0."
        ),
    )


class RiskToolOutputSchema(BaseModel):
    """
    Ouput schema for the Risk Tool.
    """

    risk_report: str = Field(
        ...,
        description="Risk report generated by the Risk Report Agent.",
    )
    risk_score: float = Field(
        ...,
        description="DeepEval DAG Risk score.",
    )
    failed_risks: List[str] = Field(
        ...,
        description="List of risks (among the input risks) found to be present.",
    )


class RiskToolConfigSchema(BaseModel):
    """
    Config schema for the Risk Tool (attribute names coincide with those of base builder input schema).
    """

    model_name: Optional[Union[RITSModels, WatsonxModels]] = Field(
        default=None,
        description="LLM to use for Risk Agent, DeepEval and Risk report agent.",
    )
    temperature: Optional[float] = Field(
        default=None,
        description="LLM temperature.",
    )
    max_tokens: Optional[int] = Field(
        default=None,
        description="LLM max tokens.",
    )
    agent_description: Optional[str] = Field(
        default=None,
        description="Description of agent being evaluated - used as behavioral context.",
    )


class RiskTool:
    name = "risk_tool"
    description = "Runs risk agent, evaluates DAG metric and generates risk report if risks are found."
    input_schema = RiskToolInputSchema
    output_schema = RiskToolOutputSchema
    config_schema = RiskToolConfigSchema

    def __init__(
        self,
        config: RiskToolConfigSchema | None = None,
        debug: bool = False,
    ):
        self.config = config or RiskToolConfigSchema()
        self.debug = debug

        # Instantiate base agents with their defaults
        default_risk_cfg = RiskAgentConfig()
        default_report_cfg = RiskReportAgentConfig()

        # Apply overrides from RiskToolConfigSchema
        merged_risk_cfg = apply_partial_config(default_risk_cfg, self.config)
        merged_report_cfg = apply_partial_config(default_report_cfg, self.config)

        # Initialize agents with merged configs
        self.risk_agent = RiskAgent(config=merged_risk_cfg, debug=debug)
        self.risk_report_agent = RiskReportAgent(config=merged_report_cfg, debug=debug)

    async def _get_risk_report_and_failed_risks(
        self,
        result: RiskAgentOutputSchema,
        inputs: List[str],
        outputs: List[str],
    ) -> Dict[str, Union[str, List]]:
        risky_content = "\n".join(
            [f"User: {i}\nModel: {o}" for i, o in zip(inputs, outputs)],
        )

        failed_criteria = self._extract_high_importance_criteria(
            result.dag_metric._verbose_steps,
        )

        risk_report_response = await self.risk_report_agent.arun(
            RiskReportAgentInputSchema(
                risky_content=risky_content,
                failed_criteria=failed_criteria,
            ),
        )

        risk_report_and_failed_risks = {
            "risk_report": risk_report_response.risk_report,
            "failed_risks": list(failed_criteria.keys()),
        }

        return risk_report_and_failed_risks

    def _extract_high_importance_criteria(
        self,
        verbose_steps: List[str],
    ) -> Dict[str, List[str]]:
        """
        Extracts criteria text from Level == 0 TaskNode entries where importance is 'high'
        AND the model's verdict was Fail, preserving the order indicated by numeric suffixes
        (e.g., positivity-bias_1, positivity-bias_2, etc.).
        Parameters
        ----------
        verbose_steps : List[str]
            The result.dag_metric._verbose_steps list.
        Returns
        -------
        Dict[str, List[str]]
            A dictionary mapping each label from the risk taxonomy (e.g., 'consistency', 'positivity-bias')
            to an ordered list of criteria that are both high-importance and failed (Fail).
        """
        criteria_by_label = defaultdict(list)

        # Regex patterns
        level_pattern = re.compile(r"Level == (\d+)")
        label_pattern = re.compile(r"Label:\s*([^\|]+)\|")
        importance_pattern = re.compile(r"importance:\s*(\w+)", re.IGNORECASE)
        instructions_pattern = re.compile(
            r"Instructions:\s*(.*?)\nAnswer strictly",
            re.DOTALL | re.IGNORECASE,
        )
        verdict_pattern = re.compile(
            r"\n([a-zA-Z0-9_\-]+):\s*(Pass|Fail)",
            re.IGNORECASE,
        )

        for block in verbose_steps:
            # Only Level == 0 nodes
            level_match = level_pattern.search(block)
            if not level_match or level_match.group(1) != "0":
                continue

            # Extract label
            label_match = label_pattern.search(block)
            if not label_match:
                continue
            label = label_match.group(1).strip()

            # Only include high importance
            importance_match = importance_pattern.search(block)
            if not importance_match or importance_match.group(1).lower() != "high":
                continue

            # Find all verdict matches
            verdict_match = verdict_pattern.findall(block)
            if not verdict_match:
                continue

            for vm in verdict_match:
                # Some malformed lines might only have one item
                if len(vm) != 2:
                    continue
                criterion_id, verdict = vm
                if verdict.lower() != "fail":
                    continue

                # Extract numeric suffix (e.g., 3 from positivity-bias_3)
                num_match = re.search(r"_(\d+)$", criterion_id)
                order = int(num_match.group(1)) if num_match else 0

                # Extract criterion text
                instructions_match = instructions_pattern.search(block)
                if instructions_match:
                    criteria_text = instructions_match.group(1).strip()
                    criteria_by_label[label].append((order, criteria_text))

        # Sort by numeric order within each label
        sorted_criteria = {
            label: [text for _, text in sorted(items, key=lambda x: x[0])]
            for label, items in criteria_by_label.items()
        }

        return sorted_criteria

    def _safe_measure_with_retries(
        self,
        dag_metric: DAGMetric,
        test_case: LLMTestCase,
        max_retries: int = 5,
        retry_delay: int = 2,
    ):
        """
        Run dag_metric.measure(test_case) with retries and error handling.
        Logs ValidationErrors.
        """
        for attempt in range(1, max_retries + 1):
            try:
                return dag_metric.measure(test_case)

            except ValidationError as e:
                logger.error(
                    f"[Attempt {attempt}/{max_retries}] Pydantic ValidationError while measuring DAG metric: {e}",
                )
                if attempt < max_retries:
                    logger.info(f"Retrying in {retry_delay} seconds...")
                    time.sleep(retry_delay)
                else:
                    logger.error("Max retries reached. Returning None.")
                    return None

            except Exception as e:
                logger.exception(f"Unexpected error while measuring DAG metric: {e}")
                return None

    def _visualize_dag_interactive(self, dag_metric: DAGMetric, output_html: str = "dag_visualization.html"):
        """
        Visualize a DAGMetric using PyVis with interactive labels and hover-over tooltips.
        Saves an HTML file and opens it in your browser.
        """
        net = Network(directed=True, notebook=False, width="100%", height="750px")
        visited = set()
        added_edges = set()

        def add_node(node: Union[TaskNode, NonBinaryJudgementNode, VerdictNode]):
            if isinstance(node, VerdictNode):
                node_id = f"verdict_{id(node)}"
                label = f"✅ {node.verdict}"
                title = f"Score: {node.score}"
            elif isinstance(node, TaskNode):
                node_id = f"node_{id(node)}"
                label = node.label if hasattr(node, "label") else node.output_label
                title = getattr(node, "instructions", "(No instructions)")
            elif isinstance(node, NonBinaryJudgementNode):
                node_id = f"node_{id(node)}"
                label = node.label if hasattr(node, "label") else node.output_label
                title = getattr(node, "criteria", "(No criteria)")
            else:
                node_id = f"node_{id(node)}"
                label = node.label if hasattr(node, "label") else node.output_label
                title = getattr(node, "instructions", "(No instructions)")

            if node_id not in visited:
                visited.add(node_id)
                net.add_node(
                    node_id,
                    label=label[:50] + "..." if len(label) > 50 else label,
                    title=title,
                    shape="box" if not isinstance(node, VerdictNode) else "ellipse",
                    color="#9fc5e8" if isinstance(node, TaskNode) else (
                        "#f6b26b" if isinstance(node, NonBinaryJudgementNode) else "#b6d7a8"
                    )
                )
            return node_id

        def recurse(node):
            src_id = add_node(node)
            for child in getattr(node, "children", []):
                tgt_id = recurse(child)
                if (src_id, tgt_id) not in added_edges:
                    net.add_edge(src_id, tgt_id)
                    added_edges.add((src_id, tgt_id))
            return src_id

        for root in dag_metric.dag.root_nodes:
            recurse(root)

        net.show_buttons(filter_=['physics'])  # Optional: show layout control
        net.show(output_html)
        print(f"DAG visualization saved to {output_html}")

    async def arun(
        self,
        params: RiskToolInputSchema,
    ) -> RiskToolOutputSchema:
        ra_result: RiskAgentOutputSchema = await self.risk_agent.arun(
            RiskAgentInputSchema(
                inputs=params.inputs,
                outputs=params.outputs,
                risk_ids=params.risk_ids,
                risk_weights=params.risk_weights,
            ),
        )
        #self._visualize_dag_interactive(ra_result.dag_metric)
        #import pdb
        #pdb.set_trace()
    
        turns = []
        for i in range(len(params.outputs) - 1):
            turns.append(f"User: {params.inputs[i]}")
            turns.append(f"Model: {params.outputs[i]}")

        turns.append(f"User: {params.inputs[-1]}")

        flattened_input = "\n".join(turns)
        actual_output = params.outputs[-1]

        test_case = LLMTestCase(
            input=flattened_input,
            actual_output=actual_output,
            context=[self.risk_agent.config.agent_description],
        )

        self._safe_measure_with_retries(ra_result.dag_metric, test_case)

        if ra_result.dag_metric.score != 1.0:
            logger.info("Risks found: Generating Risk Report")
            report_and_failed_risks = await self._get_risk_report_and_failed_risks(
                ra_result,
                params.inputs,
                params.outputs,
            )
            logger.info("Risk report generated")
            report = report_and_failed_risks.get("risk_report", "")
            failed_risks = report_and_failed_risks.get("failed_risks", [])
        else:
            logger.info(f"None of the following risks found: {params.risk_ids}")
            report = f"None of the following risks found: {params.risk_ids}"
            failed_risks = []

        return RiskToolOutputSchema(
            risk_report=report,
            failed_risks=failed_risks,
            risk_score=ra_result.dag_metric.score,
        )
